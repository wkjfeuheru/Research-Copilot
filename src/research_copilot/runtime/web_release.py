"""Pair static bytes with the actual backend, API and production dependency graph.

This is a consistency manifest, not a signature. Build and deploy directories
must be trusted. Dependency versions come from installed distribution metadata:
https://docs.python.org/3.13/library/importlib.metadata.html
https://packaging.pypa.io/en/stable/markers.html
"""

from hashlib import sha256
from importlib import metadata
import json
from pathlib import Path
import platform
import stat

from packaging.requirements import Requirement
from packaging.utils import canonicalize_name

from research_copilot import __version__
from research_copilot.runtime.identity import RUNTIME_VERSION
from research_copilot.runtime.migrations import SCHEMA_VERSION
from research_copilot.workspace.filesystem import reject_links, tree_files

API_VERSION = "1"
MANIFEST = "research-copilot-release.json"
MAX_FILE = 16 * 1024 * 1024
MAX_TOTAL = 64 * 1024 * 1024
MAX_FILES = 4096


def digest(value):
    return sha256(
        json.dumps(
            value,
            sort_keys=True,
            separators=(",", ":"),
            ensure_ascii=False,
            allow_nan=False,
        ).encode()
    ).hexdigest()


def _read(path, *, single_link=False):
    path = reject_links(Path(path))
    info = path.stat()
    if not stat.S_ISREG(info.st_mode) or (single_link and info.st_nlink != 1):
        raise ValueError("Web release requires regular, unaliased files")
    if info.st_size > MAX_FILE:
        raise ValueError("Web release file exceeds size limit")
    with path.open("rb") as stream:
        value = stream.read(MAX_FILE + 1)
    if len(value) > MAX_FILE:
        raise ValueError("Web release file exceeds size limit")
    return value


def _inventory(root, *, static=False):
    root = reject_links(Path(root)).resolve()
    values, total = {}, 0
    for path in tree_files(root):
        relative = path.relative_to(root)
        if static:
            if relative.as_posix() == MANIFEST:
                continue
        elif "__pycache__" in relative.parts or path.suffix in {".pyc", ".pyo"}:
            continue
        raw = _read(path, single_link=static)
        total += len(raw)
        if total > MAX_TOTAL or len(values) >= MAX_FILES:
            raise ValueError("Web release inventory exceeds limits")
        values[relative.as_posix()] = raw
    return values


def _hashes(files):
    return {name: sha256(raw).hexdigest() for name, raw in sorted(files.items())}


def backend_digest():
    # Includes packaged resources as well as code; ignores generated bytecode.
    return digest(_hashes(_inventory(Path(__file__).resolve().parents[1])))


def runtime_identity():
    pending = [("research-copilot", frozenset())]
    visited, packages = {}, {}
    while pending:
        name, requested = pending.pop()
        name = canonicalize_name(name)
        previous = visited.get(name)
        if previous is not None and requested <= previous:
            continue
        extras = requested | (previous or frozenset())
        visited[name] = extras
        installed = metadata.distribution(name)
        packages[name] = installed.version
        for text in installed.requires or ():
            requirement = Requirement(text)
            if requirement.marker and not any(
                requirement.marker.evaluate({"extra": extra}) for extra in {"", *extras}
            ):
                continue
            version = metadata.version(requirement.name)
            if not requirement.specifier.contains(version, prereleases=True):
                raise ValueError(
                    f"Web release dependency is incompatible: {requirement.name}"
                )
            pending.append((requirement.name, frozenset(requirement.extras)))
    if packages["research-copilot"] != __version__:
        raise ValueError("Web release application metadata mismatch")
    return {
        "application_version": __version__,
        "api_version": API_VERSION,
        "runtime_version": RUNTIME_VERSION,
        "schema_version": SCHEMA_VERSION,
        "python": {
            "version": platform.python_version(),
            "implementation": platform.python_implementation(),
            "system": platform.system(),
            "machine": platform.machine(),
        },
        "packages": dict(sorted(packages.items())),
    }


def _json(raw):
    def unique(pairs):
        result = {}
        for key, value in pairs:
            if key in result:
                raise ValueError("Duplicate web release key")
            result[key] = value
        return result

    return json.loads(raw, object_pairs_hook=unique)


def seal_web(root, *, frontend_source):
    """Explicit post-build step; refuses to overwrite an existing manifest."""
    from research_copilot.web.app import create_app

    root = reject_links(Path(root)).resolve()
    target = root / MANIFEST
    if target.exists():
        raise ValueError("Web release is already sealed; rebuild into a fresh output")
    frontend_source = reject_links(Path(frontend_source)).resolve()
    package = _json(_read(frontend_source / "package.json"))
    if (
        package.get("researchCopilotApiVersion") != API_VERSION
        or package.get("version") != __version__
    ):
        raise ValueError("Web release frontend API/application version mismatch")
    files = _inventory(root, static=True)
    if "index.html" not in files:
        raise ValueError("Web release requires index.html")
    sources = {}
    for directory in ("src", "public"):
        sources.update(
            {
                directory + "/" + name: raw
                for name, raw in _inventory(frontend_source / directory).items()
            }
        )
    for filename in (
        "package.json",
        "pnpm-lock.yaml",
        "vite.config.ts",
        "tsconfig.json",
        "index.html",
    ):
        sources[filename] = _read(frontend_source / filename)
    payload = {
        "format": 1,
        "runtime": runtime_identity(),
        "backend": backend_digest(),
        "api": digest(create_app().openapi()),
        "frontend": {
            "version": package["version"],
            "api_version": package["researchCopilotApiVersion"],
            "package_manager": package["packageManager"],
        },
        "inputs": {
            "frontend_source": digest(_hashes(sources)),
            "frontend_lock": sha256(sources["pnpm-lock.yaml"]).hexdigest(),
            "python_lock": sha256(
                _read(frontend_source.parent / "uv.lock")
            ).hexdigest(),
            "python_project": sha256(
                _read(frontend_source.parent / "pyproject.toml")
            ).hexdigest(),
        },
        "files": _hashes(files),
    }
    result = {**payload, "release_id": digest(payload)}
    # Exclusive creation: a failed or partial write fails validation and must be
    # rebuilt, rather than silently replacing the release beneath a server.
    try:
        with target.open("x", encoding="utf-8") as stream:
            json.dump(result, stream, ensure_ascii=False, indent=2)
    except FileExistsError:
        raise ValueError("Web release is already sealed") from None
    return result


def load_web_release(app, root):
    """Return verified immutable bytes and a non-sensitive diagnostic summary."""
    try:
        root = reject_links(Path(root)).resolve()
        manifest = _json(_read(root / MANIFEST, single_link=True))
        if not isinstance(manifest, dict) or set(manifest) != {
            "format",
            "runtime",
            "backend",
            "api",
            "frontend",
            "inputs",
            "files",
            "release_id",
        }:
            raise ValueError("Invalid web release structure")
        payload = {key: value for key, value in manifest.items() if key != "release_id"}
        if (
            type(manifest["format"]) is not int
            or manifest["format"] != 1
            or manifest["release_id"] != digest(payload)
        ):
            raise ValueError("Invalid web release identity")
        if (
            manifest["runtime"] != runtime_identity()
            or manifest["backend"] != backend_digest()
        ):
            raise ValueError(
                "Web release backend/runtime mismatch; rebuild with the target runtime"
            )
        if manifest["api"] != digest(app.openapi()):
            raise ValueError("Web release API schema mismatch")
        if (
            manifest["frontend"].get("api_version") != API_VERSION
            or manifest["frontend"].get("version") != __version__
        ):
            raise ValueError("Web release frontend version mismatch")
        files = _inventory(root, static=True)
        if "index.html" not in files or _hashes(files) != manifest["files"]:
            raise ValueError("Web release static inventory mismatch")
        return files, {
            "application_version": __version__,
            "api_version": API_VERSION,
            "release_id": manifest["release_id"],
            "static_verified": True,
            "backend_digest": manifest["backend"],
            "api_digest": manifest["api"],
            "runtime_digest": digest(manifest["runtime"]),
            "files": len(files),
        }
    except (OSError, KeyError, TypeError, AttributeError, json.JSONDecodeError) as exc:
        raise ValueError(
            "Invalid or missing web release; run the paired frontend build"
        ) from exc
